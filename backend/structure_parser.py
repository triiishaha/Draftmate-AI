
import re


def parse_document(markdown_text: str) -> dict:
    """
    Parse Markdown into sections and clauses.
    Expects headings generated by markdown_converter.py.
    """

    result = {
        "title": "",
        "sections": []
    }

    current_section = None
    current_clause = None

    for line in markdown_text.splitlines():
        stripped = line.strip()

        if not stripped:
            continue

        # Main document title: # SERVICE AGREEMENT
        if stripped.startswith("# ") and not stripped.startswith("## "):
            result["title"] = stripped[2:].strip()
            continue

        # Section heading: ## 1. Payment Terms
        if stripped.startswith("## "):
            current_section = {
                "section_id": f"section_{len(result['sections']) + 1}",
                "heading": stripped[3:].strip(),
                "clauses": [],
                "text": ""
            }
            result["sections"].append(current_section)
            current_clause = None
            continue

        # Clause heading: ### 1.1 Late Fees
        if stripped.startswith("### "):
            if current_section is None:
                current_section = {
                    "section_id": "section_1",
                    "heading": "Uncategorized",
                    "clauses": [],
                    "text": ""
                }
                result["sections"].append(current_section)

            heading = stripped[4:].strip()
            match = re.match(r"^(\d+(?:\.\d+)+)\s+", heading)
            clause_id = match.group(1) if match else heading

            current_clause = {
                "clause_id": clause_id,
                "heading": heading,
                "text": ""
            }
            current_section["clauses"].append(current_clause)
            continue

        # Normal paragraph text
        if current_clause is not None:
            current_clause["text"] += stripped + "\n"
        elif current_section is not None:
            current_section["text"] += stripped + "\n"

    return result
